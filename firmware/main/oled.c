/* SSD1306 / SH1106 over I²C, page addressing, 6 lines of 5x7 text.
 *
 * Hand-written rather than pulling in a graphics library: this screen shows six
 * lines of monospace text and nothing else, and a font plus twelve register
 * writes is smaller than the dependency would be. The app's look is the same
 * decision (§6) — an instrument, not a UI.
 *
 * **1.3" panels on this board are SH1106**, which is a 132-column controller
 * showing columns 2..129, so every page write starts at column 2. On an SSD1306
 * the same offset simply shifts the image 2 px right, which is why the driver
 * does not need to know which one it is talking to.
 */
#include "oled.h"

#include <stdio.h>
#include <string.h>

#include "board_pins.h"
#include "board.h"
#include "driver/i2c_master.h"
#include "esp_log.h"

static const char *TAG = "oled";

